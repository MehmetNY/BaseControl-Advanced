def parse_settings():
    src = open(os.path.join(ROOT, "src", "common", "settings_reg.cpp"), encoding="utf-8").read()
    body = src[src.index("const std::vector<SettingDef> kTable = {") + 1:]
    body = body[:body.index("\n};")]
    sections, cur = [], None
    # join the macro calls that continue on the next line
    text = re.sub(r",\s*\n\s+Ev::", ", Ev::", body)
    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"//\s*-+\s*(.*?)\s*-*$", s)
        if m and m.group(1):
            cur = {"title": m.group(1)[0].upper() + m.group(1)[1:], "rows": []}
            sections.append(cur)
            continue
        m = re.match(r"(INT|BOOL|ENUM|TEXT)\((.*)\),?$", s)
        if not m:
            continue
        kind, args = m.group(1), m.group(2)
        parts = [p.strip() for p in re.findall(r'\s*("[^"]*"|[^,]+?)\s*(?:,|$)', args)]
        key = parts[0].strip('"')
        row = {"key": key, "kind": kind}
        if kind == "INT":
            row.update(min=int(parts[1]), max=int(parts[2]), step=int(parts[3]), unit=parts[4].strip('"'), ev=parts[5][4:], cap=parts[6].strip('"'), exp=parts[7] == "true")
        elif kind == "BOOL":
            row.update(ev=parts[1][4:], cap=parts[2].strip('"'), exp=parts[3] == "true")
        elif kind == "ENUM":
            row.update(names=parts[2].strip('"'), ev=parts[3][4:], cap=parts[4].strip('"'), exp=parts[5] == "true")
        else:
            row.update(ev=parts[1][4:], cap=parts[2].strip('"'), exp=parts[3] == "true")
        cur["rows"].append(row)
    return sections


def settings_md():
    sections = parse_settings()
    keys = [r["key"] for s in sections for r in s["rows"]]
    missing = [k for k in keys if k not in DESCRIPTIONS]
    unused = [k for k in DESCRIPTIONS if k not in keys]
    if missing or unused:
        sys.exit("gen_docs.py: describe these settings in DESCRIPTIONS: %s; remove the unused entries: %s" % (missing, unused))
    o = [HEADER % "src/common/settings_reg.cpp", "# Settings\n\n",
         "Everything BaseControl can change is declared once, in `src/common/settings_reg.cpp`: a type, a range, an evidence tier and the "
         "capability that must be present. The controller refuses everything that is not in the table - there are no raw addresses and no "
         "free-form writes. A request is checked in this order: read-only switch, evidence gate, model gate, range, capability, consent, "
         "write, read-back (with rollback when the value did not stick).\n\n",
         "**Evidence tiers**\n\n"]
    for k, v in EVIDENCE.items():
        o.append("- **%s** - %s\n" % (k, v))
    o.append("\n`Capability` is the probe result the setting needs; when it is not `ok` the control stays disabled and says why. "
             "*Experimental gate* means the setting is refused until **Safety and service → Allow experimental writes** is on; on the exactly "
             "identified Tulpar T5 the *Family* settings are not gated.\n")
    for s in sections:
        o.append("\n## %s\n\n| Setting | What it does | Range | Evidence | Capability | Experimental gate |\n|---|---|---|---|---|---|\n" % s["title"].strip())
        for r in s["rows"]:
            if r["kind"] == "INT":
                rng = "%d – %d%s" % (r["min"], r["max"], (" " + r["unit"]) if r["unit"] else "")
                if r["step"] > 1:
                    rng += " (step %d)" % r["step"]
            elif r["kind"] == "BOOL":
                rng = "on / off"
            elif r["kind"] == "ENUM":
                rng = ", ".join(r["names"].split(","))
            else:
                rng = "text"
            o.append("| `%s` | %s | %s | %s | `%s` | %s |\n" % (r["key"], DESCRIPTIONS[r["key"]], rng, r["ev"], r["cap"] or "-", "yes" if r["exp"] else "no"))
    return "".join(o)


