def parse_registers():
    src = open(os.path.join(ROOT, "src", "common", "registers.h"), encoding="utf-8").read()
    sections, cur, last = [], None, None
    for line in src.splitlines():
        m = re.match(r"// ----\s*(.*?)\s*-+\s*$", line)
        if m:
            cur = {"title": m.group(1), "rows": []}
            sections.append(cur)
            last = None
            continue
        m = re.match(r"inline constexpr uint16_t (k\w+)\s*=\s*(0x[0-9A-Fa-f]+);\s*(?://\s*(.*))?$", line)
        if m and cur is not None:
            last = {"name": m.group(1), "addr": int(m.group(2), 16), "note": (m.group(3) or "").strip()}
            cur["rows"].append(last)
            continue
        m = re.match(r"\s{20,}//\s*(.*)$", line)           # a note that continues on the next line
        if m and last is not None:
            last["note"] += " " + m.group(1).strip()
    nw = re.search(r"kNeverWrite\[\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    never = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]+", re.sub(r"/\*.*?\*/", "", nw))]
    return sections, never


def registers_md():
    sections, never = parse_registers()
    o = [HEADER % "src/common/registers.h", "# Embedded-controller registers\n\n",
         "The laptop's embedded controller (EC) is reached through the `ACPIDriver` device (`\\\\.\\ACPIDriver`) that the OEM's Control Center package installs; "
         "BaseControl neither ships nor modifies that driver, so the EC features need it to be present (the Overview page shows whether the controller is reachable). "
         "Every address the program uses lives in `src/common/registers.h`; this page is generated from it. Names are the program's own and the notes say what is known about each register. "
         "**Nothing here is a vendor document**: the mappings come from the owner's measurements, the OEM "
         "Control Center's behaviour and independent open-source work on the same EC family (see [NOTICE](../NOTICE.txt)); "
         "the table does not say which source each single entry comes from.\n\n",
         "Writes never go straight to the EC: they pass the **write guard** (below), which refuses anything that is not on its allow-list.\n"]
    for s in sections:
        if not s["rows"]:
            continue                                            # the never-write list has its own section below
        title = s["title"].split(":")[0]
        o.append("\n## %s\n\n| Address | Name | Note |\n|---|---|---|\n" % (title[0].upper() + title[1:]))
        for r in s["rows"]:
            o.append("| `0x%04X` | `%s` | %s |\n" % (r["addr"], r["name"], r["note"].replace("|", "\\|")))
    o.append("\n## Never written\n\nThese addresses are refused whatever the caller says; the list wins over the allow-list:\n\n")
    o.append(", ".join("`0x%04X`" % a for a in never) + "\n\n")
    o.append("The source marks `0x0780` as the EC power-limit bypass (\"dangerous\"). It does not document what the other entries do, and this page does not guess: the program has no use for "
             "any of them, they are on the list so that a future change which puts one of them on the allow-list by mistake still cannot reach it, and nobody should write to them to find out.\n")
    o.append("""
## The write guard

`GuardedEc` (src/common/writeguard.cpp) decorates the EC driver. It also wraps the writes of the vendored MONSTER GPU POWER engine, so there is one gate for everything.

- **Allow-list with bit masks.** A register is writable only if it is on the list. A *masked* register (for example the Fn-lock byte, where only bit 4 may change) is written by read-modify-write, and the write is refused when any bit outside the mask would change.
- **Value rules.** Out-of-range values are refused, never clamped: PL1/PL2 10–210 W, PL4 raw 5–250, TCC `0x80 | 0..35`, GPU control only `0x01/0x05/0x07`, cTGP increment 0–25 W in 5 W steps, fixed fan duty `0` or `0x80 | 1..100`, battery mode `0x08/0x18/0x28`, fan-table temperatures 0–105 (or `0xFF` padding) and duties 0–200.
- **Bring-up registers** (`0x0706`, `0x0708`, `0x0709`, `0x0748`, `0x07C7`, and `0x0741 = 0x05`) are writable only inside an EC bring-up and only with their documented value. A bring-up runs only while the OEM service is stopped: automatically before a power-limit write when the EC's power-management loop is not active and you have taken over from the OEM service, or through the explicit bring-up command, which also needs *Allow experimental writes*.
- **Kill switch.** *Read-only mode* refuses every EC write.
- **Rollback.** A write that did not stick is undone; the rollback is itself checked against the register's mask.
- **Fan watchdog.** While a custom or fixed fan setting is active, the fixed duty is released and fan boost is switched on when the CPU is at 97 °C or more, or the GPU at 92 °C or more, in two consecutive one-second checks, whatever the setting says. The two temperatures are read every second even when the window is hidden.
""")
    return "".join(o)


def main():
    targets = {"docs/SETTINGS.md": settings_md(), "docs/REGISTERS.md": registers_md()}
    stale = []
    for rel, text in targets.items():
        path = os.path.join(ROOT, rel)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(rel)
            if "--check" not in sys.argv:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8", newline="\n").write(text)
                print("wrote", rel)
    if "--check" in sys.argv and stale:
        print("out of date: %s (run python3 tools/gen_docs.py)" % ", ".join(stale))
        return 1
    if "--check" in sys.argv:
        print("docs: up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
