def parse_settings():
    src = open(os.path.join(ROOT, "src", "common", "settings_reg.cpp"), encoding="utf-8").read()
    body = src[src.index("const std::vector<SettingDef> kTable = {") + 1:]
    body = body[:body.index("\n};")]
    sections, cur = [], None
    # join the macro calls that continue on the next line
    text = re.sub(r",\s*\n\s+Ev::", ", Ev::", body)
    for line in text.splitlines():
        s = line.strip()
        m = re.match(r"//\s*-+\s*(.*?)\s*-*$", s)
        if m and m.group(1):
            cur = {"title": m.group(1)[0].upper() + m.group(1)[1:], "rows": []}
            sections.append(cur)
            continue
        s = re.sub(r"\s*//.*$", "", s)   # a note at the end of the line
        m = re.match(r"(INT|BOOL|ENUM|TEXT)\((.*)\),?$", s)
        if not m:
            continue
        kind, args = m.group(1), m.group(2)
        parts = [p.strip() for p in re.findall(r'\s*("[^"]*"|[^,]+?)\s*(?:,|$)', args)]
        key = parts[0].strip('"')
        row = {"key": key, "kind": kind}
        if kind == "INT":
            row.update(min=int(parts[1]), max=int(parts[2]), step=int(parts[3]), unit=parts[4].strip('"'), ev=parts[5][4:], cap=parts[6].strip('"'))
        elif kind == "BOOL":
            row.update(ev=parts[1][4:], cap=parts[2].strip('"'))
        elif kind == "ENUM":
            row.update(names=parts[2].strip('"'), ev=parts[3][4:], cap=parts[4].strip('"'))
        else:
            row.update(ev=parts[1][4:], cap=parts[2].strip('"'))
        cur["rows"].append(row)
    return sections


def settings_md():
    sections = parse_settings()
    keys = [r["key"] for s in sections for r in s["rows"]]
    missing = [k for k in keys if k not in DESCRIPTIONS]
    unused = [k for k in DESCRIPTIONS if k not in keys]
    if missing or unused:
        sys.exit("gen_docs.py: describe these settings in DESCRIPTIONS: %s; remove the unused entries: %s" % (missing, unused))
    o = [HEADER % "src/common/settings_reg.cpp", "# Settings\n\n",
         "Everything Control Center Advanced can change is declared once, in `src/common/settings_reg.cpp`: a type, a range, an evidence tier and the "
         "capability that must be present. The controller refuses everything that is not in the table - there are no raw addresses and no "
         "free-form writes. A request is checked in this order: the key and its range, the capability, the read-only switch, the consent for "
         "a risky value, the rule that profile values are only written while the Custom mode is active, the write, and finally the read-back "
         "(a GPU power change that did not stick is undone).\n\n",
         "The ranges in the table are the outer limits the program will ever send. For the values of the Custom mode the vendor's service states "
         "the real limits of the active profile, and those are enforced as well.\n\n",
         "**Evidence tiers**\n\n"]
    for k, v in EVIDENCE.items():
        o.append("- **%s** - %s\n" % (k, v))
    o.append("\n`Capability` is the probe result the setting needs; when it is not `ok` the control stays disabled and says why "
             "(`offline` means the vendor's service cannot be reached, `pending` that it has not reported yet).\n")
    for s in sections:
        o.append("\n## %s\n\n| Setting | What it does | Range | Evidence | Capability |\n|---|---|---|---|---|\n" % s["title"].strip())
        for r in s["rows"]:
            if r["kind"] == "INT":
                rng = "%d – %d%s" % (r["min"], r["max"], (" " + r["unit"]) if r["unit"] else "")
                if r["step"] > 1:
                    rng += " (step %d)" % r["step"]
            elif r["kind"] == "BOOL":
                rng = "on / off"
            elif r["kind"] == "ENUM":
                rng = ", ".join(r["names"].split(","))
            else:
                rng = "text"
            o.append("| `%s` | %s | %s | %s | `%s` |\n" % (r["key"], DESCRIPTIONS[r["key"]], rng, r["ev"], r["cap"] or "-"))
    return "".join(o)


